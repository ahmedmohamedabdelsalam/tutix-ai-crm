require('dotenv').config();
const Anthropic = require('@anthropic-ai/sdk').default;
const client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });

const history = [
  { role: 'user', content: 'السلام عليكم' },
  { role: 'assistant', content: 'ورحمة الله وبركاته\n\nتشرفنا باسم حضرتك؟' },
  { role: 'user', content: 'أحمد' },
];

async function testPrompt(label, systemPrompt) {
  const response = await client.messages.create({
    model: 'claude-haiku-4-5-20251001',
    max_tokens: 150,
    temperature: 0.3,
    system: systemPrompt,
    messages: history,
  });
  const text = response.content[0]?.text || '(EMPTY)';
  console.log(`[${label}] content_len=${response.content.length} stop=${response.stop_reason} reply="${text.substring(0,80)}"`);
}

